import {PGlite} from '@electric-sql/pglite';
import {readFile} from 'node:fs/promises';
import assert from 'node:assert/strict';
const db=new PGlite();
await db.exec(`create role anon;create role authenticated;create role service_role;
create table dashboard_accounts(id uuid primary key,role text);
create table fulfilment_orders(id text primary key,status text,data jsonb);
create table production_batches(id uuid primary key,production_date date,cutoff_at timestamptz,pickup_date date,created_by uuid);
create table production_items(id uuid primary key default gen_random_uuid(),batch_id uuid,order_id text unique,stage text default 'received',disposition text default 'active',deferred_until date,carried_issue text,issue text default '',version int default 1,updated_at timestamptz default now());
create table production_events(item_id uuid,stage text,kind text,note text,actor uuid);
create function bc_v2_require_staff(uuid) returns void language plpgsql as $$begin if not exists(select 1 from dashboard_accounts where id=$1)then raise exception 'Staff required';end if;end$$;
insert into dashboard_accounts values('11111111-1111-4111-8111-111111111111','admin');
insert into fulfilment_orders values('new','new_order',jsonb_build_object('orderDate',now()-interval '1 minute')),('old','uploading_audio',jsonb_build_object('orderDate',now()-interval '1 day'));
grant select,insert,update on all tables in schema public to service_role;`);
await db.exec(await readFile(new URL('../supabase/migrations/20261102180000_production_batches_anytime.sql',import.meta.url),'utf8'));
await db.exec('set role service_role');
const create=(id,orders)=>db.query(`select production_create_batch('11111111-1111-4111-8111-111111111111',$1,(now() at time zone 'Asia/Kuala_Lumpur')::date+1,$2)`,[id,orders]);
const batch='22222222-2222-4222-8222-222222222222';
await create(batch,['new']); // Tomorrow's date used to require waiting until tomorrow at 10pm.
assert.equal((await db.query('select count(*)::int n from production_items')).rows[0].n,1);
assert.equal((await db.query('select abs(extract(epoch from (now()-cutoff_at)))<10 fresh from production_batches')).rows[0].fresh,true);
await create(batch,['new']);
assert.equal((await db.query('select count(*)::int n from production_items')).rows[0].n,1);
await assert.rejects(create('33333333-3333-4333-8333-333333333333',['old']),/no longer eligible/);
await assert.rejects(create('44444444-4444-4444-8444-444444444444',['new']),/already in a production queue/);
assert.equal((await db.query('select count(*)::int n from production_batches')).rows[0].n,1);
await db.exec('reset role;set role anon');
await assert.rejects(create('55555555-5555-4555-8555-555555555555',['new']),/permission denied/);
await db.close();console.log('Anytime batch creation, real creation timestamp, retry safety, stage guards, duplicate protection and access checks passed.');
