import {PGlite} from '@electric-sql/pglite';
import {readFile} from 'node:fs/promises';
import assert from 'node:assert/strict';
const db=new PGlite();
await db.exec(`create role anon;create role authenticated;create schema internal;
create table fulfilment_orders(id text primary key,data jsonb);
create table customisation_sessions(id int primary key,fulfilment_order_id text,certificate_code text,certificate_metaobject_id text);`);
await db.exec(await readFile(new URL('../supabase/migrations/20261102165733_protect_shared_1970_certificate_choices.sql',import.meta.url),'utf8'));
await db.exec(`insert into fulfilment_orders values ('1970-1','{"certificateCode":"19701698520","status":"shipped"}'),('1970-2','{"certificateCode":"19701698520"}'),('other','{"certificateCode":"19701698520"}');
insert into customisation_sessions values(1,'1970-1','19701698520','root'),(2,'other','unrelated','untouched');
update customisation_sessions set certificate_code='19701698520-1',certificate_metaobject_id='child-one' where id=1;
update customisation_sessions set certificate_code='19701698520',certificate_metaobject_id='root' where id=1;
update customisation_sessions set certificate_code='changed' where id=2;
update fulfilment_orders set data=data||'{"certificateCode":"19701698520"}' where id='1970-1';`);
const orders=(await db.query('select * from fulfilment_orders order by id')).rows;
assert.equal(orders[0].data.certificateCode,'19701698520-1');assert.equal(orders[0].data.status,'shipped');
assert.equal(orders[1].data.certificateCode,'19701698520-2');assert.equal(orders[2].data.certificateCode,'19701698520');
const sessions=(await db.query('select * from customisation_sessions order by id')).rows;
assert.equal(sessions[0].certificate_code,'19701698520-1');assert.equal(sessions[0].certificate_metaobject_id,'child-one');assert.equal(sessions[1].certificate_code,'changed');
await db.close();console.log('Specific-order certificate separation survives old imports; other orders and statuses are unchanged.');
