-- Access is through the authenticated warehouse API only. Public taps resolve
-- one opaque token on the server; neither inventory nor audit is public.
create table public.nfc_card_batches (
  id uuid primary key,
  number bigint generated always as identity unique,
  quantity integer not null check (quantity between 1 and 1000),
  created_at timestamptz not null default now(),
  created_by text not null
);
create table public.nfc_cards (
  id bigint generated by default as identity (start with 100001) primary key,
  batch_id uuid not null references public.nfc_card_batches(id),
  public_token text not null unique default replace(gen_random_uuid()::text,'-',''),
  status text not null default 'available' check(status in ('available','assigned','voided')),
  order_id text references public.fulfilment_orders(id) on delete restrict,
  programmed_at timestamptz,
  programmed_by text,
  paired_at timestamptz,
  paired_by text,
  created_at timestamptz not null default now(),
  check (status <> 'assigned' or (order_id is not null and programmed_at is not null and paired_at is not null))
);
create unique index nfc_one_active_card_per_order on public.nfc_cards(order_id) where status='assigned';
create index nfc_cards_batch_idx on public.nfc_cards(batch_id,id);
create index nfc_cards_order_idx on public.nfc_cards(order_id);
create table public.nfc_pairing_logs (
  id bigint generated always as identity primary key,
  card_id bigint not null references public.nfc_cards(id),
  order_id text,
  action text not null check(action in ('programmed','paired','unpaired','voided')),
  actor text not null,
  reason text not null default '',
  created_at timestamptz not null default now()
);
create index nfc_pairing_logs_card_idx on public.nfc_pairing_logs(card_id,id desc);
alter table public.nfc_card_batches enable row level security;
alter table public.nfc_cards enable row level security;
alter table public.nfc_pairing_logs enable row level security;
revoke all on public.nfc_card_batches, public.nfc_cards, public.nfc_pairing_logs from public,anon,authenticated;
grant select,insert,update on public.nfc_card_batches,public.nfc_cards to service_role;
grant select,insert on public.nfc_pairing_logs to service_role;
grant usage,select on sequence public.nfc_card_batches_number_seq,public.nfc_cards_id_seq,public.nfc_pairing_logs_id_seq to service_role;

create function internal.nfc_destination(d jsonb) returns text
language plpgsql immutable security invoker set search_path='' as $$
declare link text; charm boolean;
begin
  charm := coalesce(d->>'productType','') in ('plush_charm','snowy_charm') or concat_ws(' ',d->>'product',d->>'remark') ~* '\mplush\s*charms?\M';
  if not charm and btrim(coalesce(d->>'certificateCode','')) ~ '^[A-Za-z0-9_-]+$' then
    return 'https://meaningfulplushies.com/pages/certificate/'||btrim(d->>'certificateCode');
  end if;
  link := btrim(coalesce(d->>'idWebsiteLink',''));
  if link='' then return null; end if;
  if link !~ '^https?://' then link := 'https://'||link; end if;
  if link ~ '^https://(www\.)?meaningfulplushies\.com/(pages/certificate/[A-Za-z0-9_-]+/?|apps/closer/?(\?[^[:space:]]*)?)$' then return link; end if;
  return null;
end;
$$;

create function public.generate_nfc_cards(p_batch uuid,p_quantity integer,p_actor text) returns uuid
language plpgsql security invoker set search_path='' as $$
declare b public.nfc_card_batches;
begin
  if p_batch is null or p_quantity is null or p_quantity not between 1 and 1000 or btrim(coalesce(p_actor,''))='' then raise exception 'INVALID_NFC_BATCH'; end if;
  insert into public.nfc_card_batches(id,quantity,created_by) values(p_batch,p_quantity,p_actor) on conflict(id) do nothing;
  select * into b from public.nfc_card_batches where id=p_batch for update;
  if b.quantity<>p_quantity or b.created_by<>p_actor then raise exception 'NFC_BATCH_CHANGED'; end if;
  if not exists(select 1 from public.nfc_cards where batch_id=p_batch) then
    insert into public.nfc_cards(batch_id) select p_batch from generate_series(1,p_quantity);
  end if;
  return p_batch;
end;
$$;

-- MPI identifies a fulfilment row (one plushie), unlike legacy order barcodes
-- which can be shared by several plushies. Ambiguous scans always stop.
create function public.resolve_nfc_order(p_scan text) returns jsonb
language plpgsql security invoker set search_path='' as $$
declare scan text := btrim(p_scan); matches text[]; o public.fulfilment_orders; card bigint;
begin
  if scan is null or length(scan) not between 1 and 512 then raise exception 'INVALID_SCAN'; end if;
  if upper(scan) like 'MPI-%' then
    select array_agg(id) into matches from (select id from public.fulfilment_orders where upper(id)=substring(upper(scan) from 5) limit 2) x;
  elsif scan ~ '^https://(www\.)?meaningfulplushies\.com/' then
    select array_agg(id) into matches from (select id from public.fulfilment_orders where internal.nfc_destination(data)=scan limit 2) x;
  else
    scan := regexp_replace(upper(scan),'[^A-Z0-9]','','g');
    select array_agg(id) into matches from (
      select id from public.fulfilment_orders where
        regexp_replace(upper(id),'[^A-Z0-9]','','g')=scan
        or regexp_replace(upper(data->>'orderNumber'),'[^A-Z0-9]','','g')=scan
        or ('MP'||case when data->>'salesChannel'='tiktok' and upper(data->>'orderNumber') ~ '\mTT[0-9]+\M'
          then substring(upper(data->>'orderNumber') from '\mTT[0-9]+\M')
          else regexp_replace(upper(data->>'orderNumber'),'[^A-Z0-9]','','g') end)=scan
      limit 2
    ) x;
  end if;
  if coalesce(array_length(matches,1),0)=0 then raise exception 'NFC_ORDER_NOT_FOUND'; end if;
  if array_length(matches,1)>1 then raise exception 'NFC_ORDER_AMBIGUOUS'; end if;
  select * into o from public.fulfilment_orders where id=matches[1];
  select id into card from public.nfc_cards where order_id=o.id and status='assigned';
  return jsonb_build_object('id',o.id,'orderNumber',o.data->>'orderNumber','plushName',o.data->>'plushName',
    'customerName',o.data->>'customerName','character',o.data->>'character','status',o.status,'cardId',card);
end;
$$;

create function public.mutate_nfc_card(p_action text,p_card bigint,p_order text,p_actor text,p_reason text default '') returns jsonb
language plpgsql security invoker set search_path='' as $$
declare c public.nfc_cards; o public.fulfilment_orders; target text; prior text; charm boolean;
begin
  if p_action is null or p_action not in ('programmed','pair','unpair','void') or btrim(coalesce(p_actor,''))='' then raise exception 'INVALID_NFC_ACTION'; end if;
  -- All actions lock a card before its order. The per-order unique index also
  -- protects two simultaneous scans of different cards for the same plushie.
  select * into c from public.nfc_cards where id=p_card for update;
  if not found then raise exception 'NFC_CARD_NOT_FOUND'; end if;
  prior := c.order_id;
  if p_action='programmed' then
    if c.status='voided' then raise exception 'NFC_CARD_VOIDED'; end if;
    if c.programmed_at is not null then return to_jsonb(c); end if;
    update public.nfc_cards set programmed_at=now(),programmed_by=p_actor where id=c.id;
  elsif p_action='pair' then
    if c.status='voided' then raise exception 'NFC_CARD_VOIDED'; end if;
    if c.status='assigned' then
      if c.order_id=p_order then return to_jsonb(c); end if;
      raise exception 'NFC_CARD_ALREADY_ASSIGNED';
    end if;
    if c.programmed_at is null then raise exception 'NFC_CARD_NOT_PROGRAMMED'; end if;
    select * into o from public.fulfilment_orders where id=p_order for update;
    if not found then raise exception 'NFC_ORDER_NOT_FOUND'; end if;
    if o.status not in ('new_order','uploading_audio','sent_for_sewing','packed') then raise exception 'NFC_ORDER_NOT_READY'; end if;
    target := internal.nfc_destination(o.data);
    if target is null then raise exception 'NFC_CERTIFICATE_MISSING'; end if;
    charm := coalesce(o.data->>'productType','') in ('plush_charm','snowy_charm') or concat_ws(' ',o.data->>'product',o.data->>'remark') ~* '\mplush\s*charms?\M';
    if not charm and (btrim(coalesce(o.data->>'plushName',''))='' or btrim(coalesce(o.data->>'character',''))='') then raise exception 'NFC_ORDER_NOT_READY'; end if;
    if exists(select 1 from public.certificate_sync_jobs where order_id=o.id and revision>synced_revision) then raise exception 'NFC_CERTIFICATE_PENDING'; end if;
    if exists(select 1 from public.fulfilment_orders where id<>o.id and internal.nfc_destination(data)=target) then raise exception 'NFC_CERTIFICATE_SHARED'; end if;
    if exists(select 1 from public.nfc_cards where order_id=o.id and status='assigned') then raise exception 'NFC_ORDER_ALREADY_PAIRED'; end if;
    update public.nfc_cards set status='assigned',order_id=o.id,paired_at=now(),paired_by=p_actor where id=c.id;
    prior := o.id;
  else
    if btrim(coalesce(p_reason,''))='' or length(p_reason)>500 then raise exception 'NFC_REASON_REQUIRED'; end if;
    if c.order_id is distinct from nullif(p_order,'') then raise exception 'NFC_CARD_CHANGED'; end if;
    if p_action='unpair' then
      if c.status<>'assigned' then raise exception 'NFC_CARD_NOT_ASSIGNED'; end if;
      update public.nfc_cards set status='available',order_id=null,paired_at=null,paired_by=null where id=c.id;
    else
      if c.status='voided' then return to_jsonb(c); end if;
      update public.nfc_cards set status='voided' where id=c.id;
    end if;
  end if;
  insert into public.nfc_pairing_logs(card_id,order_id,action,actor,reason)
    values(c.id,prior,case p_action when 'pair' then 'paired' when 'unpair' then 'unpaired' when 'void' then 'voided' else 'programmed' end,p_actor,coalesce(p_reason,''));
  return (select to_jsonb(x) from public.nfc_cards x where id=c.id);
end;
$$;
revoke all on function internal.nfc_destination(jsonb),public.generate_nfc_cards(uuid,integer,text),public.resolve_nfc_order(text),public.mutate_nfc_card(text,bigint,text,text,text) from public,anon,authenticated;
grant usage on schema internal to service_role;
grant execute on function internal.nfc_destination(jsonb),public.generate_nfc_cards(uuid,integer,text),public.resolve_nfc_order(text),public.mutate_nfc_card(text,bigint,text,text,text) to service_role;

-- A batch can explicitly use prewritten stock instead of writing a customer's
-- link before sewing. Those items must be paired at the final packing station.
alter table public.fulfilment_batches add column nfc_mode text not null default 'direct' check(nfc_mode in ('direct','prewritten'));
create table public.nfc_pairing_requirements (
  order_id text primary key references public.fulfilment_orders(id) on delete restrict,
  batch_id uuid not null references public.fulfilment_batches(id),
  created_at timestamptz not null default now()
);
create index nfc_pairing_requirements_batch_idx on public.nfc_pairing_requirements(batch_id);
alter table public.nfc_pairing_requirements enable row level security;
revoke all on public.nfc_pairing_requirements from public,anon,authenticated;
grant select,insert on public.nfc_pairing_requirements to service_role;

create function public.prepare_prewritten_nfc_batch(p_batch uuid,p_version integer,p_actor text) returns uuid
language plpgsql security invoker set search_path='' as $$
declare b public.fulfilment_batches; transitions jsonb;
begin
  select * into b from public.fulfilment_batches where id=p_batch for update;
  if not found then raise exception 'BATCH_NOT_FOUND'; end if;
  if b.stage='complete' and b.nfc_mode='prewritten' then return b.id; end if;
  if b.version<>p_version then raise exception 'BATCH_CHANGED'; end if;
  if b.stage<>'nfc' then raise exception 'INVALID_STAGE'; end if;
  if not exists(select 1 from public.fulfilment_batch_orders where batch_id=b.id) then raise exception 'INVALID_ORDERS'; end if;
  if exists(select 1 from public.fulfilment_batch_orders where batch_id=b.id and nfc_written_at is not null) then raise exception 'NFC_BATCH_ALREADY_WRITING'; end if;
  perform o.id from public.fulfilment_orders o join public.fulfilment_batch_orders m on m.order_id=o.id where m.batch_id=b.id order by o.id for update of o;
  if exists(select 1 from public.fulfilment_orders o join public.fulfilment_batch_orders m on m.order_id=o.id where m.batch_id=b.id and o.status<>'uploading_audio') then raise exception 'ORDER_STAGE_CHANGED'; end if;
  insert into public.nfc_pairing_requirements(order_id,batch_id) select order_id,batch_id from public.fulfilment_batch_orders where batch_id=b.id on conflict(order_id) do nothing;
  select jsonb_agg(jsonb_build_object('orderId',o.id,'fromStatus','uploading_audio','toStatus','sent_for_sewing','note','Prewritten NFC card must be paired at packing')) into transitions
    from public.fulfilment_orders o join public.fulfilment_batch_orders m on m.order_id=o.id where m.batch_id=b.id;
  perform public.transition_fulfilment_orders(transitions,p_actor);
  update public.fulfilment_batches set nfc_mode='prewritten',stage='complete',completed_at=now(),version=version+1 where id=b.id;
  insert into public.fulfilment_batch_events(batch_id,action,actor,batch_version,details) values(b.id,'prewritten_nfc',p_actor,b.version+1,jsonb_build_object('pairAtPacking',true));
  return b.id;
end;
$$;
revoke all on function public.prepare_prewritten_nfc_batch(uuid,integer,text) from public,anon,authenticated;
grant execute on function public.prepare_prewritten_nfc_batch(uuid,integer,text) to service_role;

create function internal.require_nfc_pairing_at_packing() returns trigger
language plpgsql security invoker set search_path='' as $$
begin
  if new.status in ('packed','shipped') and new.status is distinct from old.status
    and exists(select 1 from public.nfc_pairing_requirements where order_id=new.id)
    and not exists(select 1 from public.nfc_cards where order_id=new.id and status='assigned') then
    raise exception 'Pair this plushie with its NFC card before marking it packed or shipped.';
  end if;
  return new;
end;
$$;
revoke all on function internal.require_nfc_pairing_at_packing() from public,anon,authenticated;
create trigger zz_nfc_pairing_at_packing before update on public.fulfilment_orders
for each row execute function internal.require_nfc_pairing_at_packing();
