  (() => {
    const reviews = document.currentScript.previousElementSibling.previousElementSibling;
    const track = reviews.querySelector('.mp-review-track');
    const cards = [...track.children];
    const dotsContainer = reviews.querySelector('.mp-review-status [aria-hidden]');
    const dots = reviews.hasAttribute('data-loop') ? [] : cards.map(() => dotsContainer.appendChild(document.createElement('i')));
    const counter = reviews.querySelector('[aria-live]');
    let active = Math.max(0, cards.findIndex((card) => card.hasAttribute('data-active')));
    const title = reviews.querySelector('h2');
    const firstLine = title.firstElementChild;

    function fitTitle() {
      const available = title.clientWidth;
      if (!available) return;
      const max = Math.min(76, window.innerHeight * .115);
      title.style.setProperty('--review-title-size', max + 'px');
      const measured = firstLine.getBoundingClientRect().width;
      if (measured > available) {
        title.style.setProperty('--review-title-size', (max * (available - 1) / measured) + 'px');
      }
    }
    if ('ResizeObserver' in window) {
      const observer = new ResizeObserver(fitTitle);
      observer.observe(reviews);
    }
    document.fonts?.ready.then(fitTitle);
    fitTitle();

    const loop = reviews.hasAttribute('data-loop') && cards.length > 1;
    const reducedMotion = matchMedia('(prefers-reduced-motion: reduce)');
    const section = reviews.closest('.shopify-section');
    const listeners = new AbortController();
    const { signal } = listeners;
    let visible = false;
    let muted = false;
    let playing = null;
    let settleTimer;
    let pending = null;

    function cloneCard(card) {
      const clone = card.cloneNode(true);
      const video = clone.querySelector('video');
      if (video && card.dataset.videoPoster) {
        const poster = new Image();
        poster.src = card.dataset.videoPoster;
        poster.alt = '';
        video.replaceWith(poster);
      }
      clone.inert = true;
      clone.setAttribute('aria-hidden', 'true');
      clone.removeAttribute('data-active');
      return clone;
    }
    if (loop) {
      track.prepend(cloneCard(cards.at(-1)));
      track.append(cloneCard(cards[0]));
    }
    const slides = [...track.children];

    function go(card, behavior) {
      track.scrollTo({ left: card.offsetLeft + (card.offsetWidth - track.clientWidth) / 2, behavior });
    }

    function syncAudio(video) {
      const button = video.closest('figure').querySelector('[data-review-audio]');
      button.textContent = video.muted ? 'Unmute' : 'Mute';
      button.setAttribute('aria-label', button.textContent + ' review audio');
    }

    function playActive() {
      const video = visible ? cards[active].querySelector('video') : null;
      if (playing === video) return;
      playing?.pause();
      playing = video;
      if (!video) return;
      video.muted = muted;
      syncAudio(video);
      video.play().catch(() => {
        if (playing !== video || video.muted) return;
        video.muted = true;
        syncAudio(video);
        video.play().catch(() => {});
      });
    }

    function update() {
      const center = track.scrollLeft + track.clientWidth / 2;
      let nearest = Infinity;
      let current;
      for (const slide of slides) {
        const distance = Math.abs(slide.offsetLeft + slide.offsetWidth / 2 - center);
        if (distance < nearest) {
          nearest = distance;
          current = slide;
        }
        slide.removeAttribute('data-active');
      }
      current?.setAttribute('data-active', '');
      const index = cards.indexOf(current);
      if (index < 0) return current;
      active = index;
      cards.forEach((card, cardIndex) => {
        const audio = card.querySelector('[data-review-audio]');
        if (audio) audio.hidden = cardIndex !== active;
        dots[cardIndex]?.toggleAttribute('data-active', cardIndex === active);
      });
      const label = String(active + 1).padStart(2, '0') + ' / ' + String(cards.length).padStart(2, '0');
      if (counter.textContent !== label) counter.textContent = label;
      playActive();
      return current;
    }

    function settle() {
      pending = null;
      const current = update();
      if (loop && current === slides[0]) go(cards.at(-1), 'instant');
      if (loop && current === slides.at(-1)) go(cards[0], 'instant');
      update();
    }

    const observer = new IntersectionObserver(([entry]) => {
      visible = entry.isIntersecting && entry.intersectionRatio >= .5;
      playActive();
    }, { threshold: .5 });
    observer.observe(track);
    section?.addEventListener('shopify:section:unload', () => {
      listeners.abort();
      observer.disconnect();
      clearTimeout(settleTimer);
      playing?.pause();
    }, { once: true });

    track.addEventListener('scroll', () => {
      update();
      clearTimeout(settleTimer);
      settleTimer = setTimeout(settle, 130);
    }, { passive: true, signal });
    reviews.addEventListener('click', (event) => {
      const audio = event.target.closest('[data-review-audio]');
      if (audio) {
        const video = audio.closest('figure').querySelector('video');
        muted = !video.muted;
        video.muted = muted;
        syncAudio(video);
        if (!muted) video.play().catch(() => {});
        return;
      }
      const button = event.target.closest('[data-step]');
      if (!button || pending) return;
      const index = active + Number(button.dataset.step);
      const card = cards[index] || (loop ? slides.at(index < 0 ? 0 : -1) : null);
      if (!card) return;
      pending = card;
      go(card, reducedMotion.matches ? 'instant' : 'smooth');
      clearTimeout(settleTimer);
      settleTimer = setTimeout(settle, 180);
    }, { signal });
    requestAnimationFrame(() => { go(cards[active], 'instant'); update(); });
  })();
