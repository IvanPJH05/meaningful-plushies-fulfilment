      const columns = Number(holder.dataset.columns);
      const width = image.naturalWidth / columns;
      const height = width * canvas.height / canvas.width;
      const cell = index % 16;
      context.clearRect(0, 0, canvas.width, canvas.height);
      context.drawImage(image, (cell % columns) * width, Math.floor(cell / columns) * height, width, height, 0, 0, canvas.width, canvas.height);
